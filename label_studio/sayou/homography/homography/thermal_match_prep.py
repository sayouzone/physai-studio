"""열화상 매칭용 전처리 — 온도 변화에 강인한 표현으로 바꾼다.

배경 (실측으로 확정)
--------------------
EWP-서오창IC-2 IR 에서 중앙의 폭 6 m 세로 띠 하나가 계속 찢어졌습니다.
그 자리는 왕복 스캔의 **인접 비행선이 만나는 경계**입니다.

파이프라인에 매칭 진단을 넣어 재봤습니다.

| | 쌍 수 | 성공률 | 쌍당 대응 중앙값 |
|---|---|---|---|
| 비행선 내부 | 1,306 | 88.4 % | **258개** |
| 비행선 교차 | 2,536 | 81.0 % | **104개** |

**성공률은 비슷한데 대응 개수가 40% 수준**입니다. 겹침 기하 탓이
아닙니다 — 겹침 비율은 교차 72%, 내부 72% 로 같고 교차 쪽이 오히려
더 넓습니다(18.9 m vs 15.2 m).

원본 10장으로 촬영 시각차별 대응 수를 직접 쟀습니다.

| 전처리 | 시각차 <60초 | 시각차 ≥60초 |
|---|---|---|
| 원본 | 124 | **7** |
| **기울기(σ2.0)** | **221** | 9 |

(RANSAC 통과 후 유효 대응 중앙값)

**IR 은 1분만 지나도 온도 패턴이 달라져 같은 지점을 못 알아봅니다.**
전처리로도 먼 쌍(≥60초)은 못 살립니다 — 영상에 남은 정보 자체가
다릅니다. 다만 **가까운 쌍은 124 → 221 로 78% 늘어납니다.**

왜 기울기인가
------------
IR 픽셀값은 절대 온도입니다. 시간이 지나면 전체가 데워지거나 식어
값 자체가 통째로 이동합니다. **기울기(공간 미분)는 그 전역 변화에
영향받지 않고 구조(패널 경계·프레임)만 남깁니다.**

CLAHE 와 무엇이 다른가
---------------------
앞서 CLAHE 를 시도했다가 실패했습니다 — 전처리한 이미지를 **JPEG 로
재저장**해 파이프라인에 넣었더니 BA 점군이 1/76 로 붕괴했습니다
(원인은 끝내 규명 못 했습니다).

이 모듈은 **파일을 만들지 않습니다.** 매칭 단계에서 메모리 안에서만
변환하므로 재저장 경로를 아예 타지 않습니다. 온도값도 원본 그대로
유지되어 결함 판독에 영향이 없습니다.

연결 방법
--------
이 함수를 특징점 검출 **직전**에 끼워 넣으면 됩니다. `features` 모듈이
이 트리에 없어 자동 연결은 하지 않았습니다 — 직접 연결하실 때
`build_tie_points` 안에서 `cv2.imread(...)` 로 읽은 회색조 배열을
`thermal_gradient()` 에 통과시킨 뒤 SIFT 에 넘기면 됩니다.

원본 픽셀값은 매칭에만 쓰이고 모자이크는 원본으로 그려지므로, 이
변환이 최종 산출물의 온도값을 바꾸지 않습니다.
"""

from __future__ import annotations

import logging

import numpy as np

logger = logging.getLogger(__name__)

__all__ = ["thermal_gradient"]


def thermal_gradient(image: np.ndarray, *, sigma: float = 2.0) -> np.ndarray:
    """열화상을 **기울기 크기** 영상으로 바꾼다 (매칭 전용).

    절대 온도가 아니라 공간 구조만 남기므로, 촬영 시각차로 전체 온도가
    이동해도 같은 지점이 비슷하게 보인다.

    Parameters
    ----------
    image : 회색조 2-D 배열. 컬러가 들어오면 회색조로 바꾼다.
    sigma : 사전 평활 강도. 실측에서 2.0 이 1.2 보다 나았다
        (대응 193 → 221). 열화상은 노이즈가 많아 어느 정도 뭉개는 편이
        특징점 품질에 유리하다.

    Returns
    -------
    uint8 배열. 원본과 같은 크기.
    """
    import cv2

    im = np.asarray(image)
    if im.ndim == 3:
        im = cv2.cvtColor(im[:, :, :3], cv2.COLOR_BGR2GRAY)
    f = cv2.GaussianBlur(im.astype(np.float32), (0, 0), sigma)
    gx = cv2.Sobel(f, cv2.CV_32F, 1, 0, ksize=3)
    gy = cv2.Sobel(f, cv2.CV_32F, 0, 1, ksize=3)
    g = np.hypot(gx, gy)
    # 상위 1% 로 정규화 — 소수의 극단값에 스케일이 끌려가지 않게 한다.
    scale = float(np.percentile(g, 99)) + 1e-6
    return np.clip(g / scale * 255.0, 0, 255).astype(np.uint8)
